/** Every GoTipe interface key; the block editor's strings ship in `@gotipe/block-editor`. */
export type TranslationKey = BaseTranslationKey | BlockEditorTranslationKey;

/**
 * A dictionary: every base key, and any block editor keys it overrides. Block editor keys it
 * leaves out come from `@gotipe/block-editor`'s own tables.
 */
export type Locale = Record<BaseTranslationKey, string> &
  Partial<Record<BlockEditorTranslationKey, string>>;

export type PluralKeyBase =
  | "review.proposals"
  | "review.staleCount"
  // --- version history (frame 30) ---
  | "history.changed"
  // --- frames 25–28 ---
  | "status.words"
  | "status.characters"
  | "status.charactersOf"
  | "status.limit";

export interface I18n {
  t(key: TranslationKey, params?: Record<string, string | number>): string;
  /** Plural form by CLDR rules of the locale: `{base}.one|few|many`. */
  plural(base: PluralKeyBase, count: number, params?: Record<string, string | number>): string;
  locale: string;
  setLocale(locale: string): void;
  addLocale(name: string, translations: Locale): void;
}
